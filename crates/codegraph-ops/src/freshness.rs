//! Generator-rev freshness (#357).
//!
//! After regeneration the generator stamps `.codegraph-manifest.json` at the
//! output root with the checkout rev it ran from (JSON field
//! `codegraphCommit`; `codegraph-generate::manifest::Manifest`). The
//! generated testkit crate pins codegraph-ops at the same rev as the other
//! codegraph crates, and this crate's `build.rs` embeds that pinned rev at
//! build time (`CODEGRAPH_OPS_REV`). Comparing the two catches a stale graph
//! binary deterministically — the stale-debug-binary incident (generation ran
//! under an old debug graph binary) becomes a hard error instead of drifting
//! output discovered minutes later.
//!
//! Degradation contract (backward compatible, never spuriously fatal):
//! - missing manifest / missing or empty `codegraphCommit` (older
//!   generators) → warn, continue;
//! - empty embedded rev (path-dep or non-git testkit build) → warn, continue;
//! - mismatch → hard error naming BOTH revs + the manifest path, or a warning
//!   under `--allow-gen-rev-mismatch`.

use std::path::Path;

use crate::error::{OpsError, OpsResult};
use crate::output;

/// Generator manifest written at every output root by codegraph-generate
/// (`codegraph-generate::manifest::MANIFEST_FILENAME`).
pub const GEN_MANIFEST_FILENAME: &str = ".codegraph-manifest.json";

/// JSON field carrying the generator's git rev (serde-renamed camelCase in
/// `codegraph-generate::manifest::Manifest`).
pub const CODEGRAPH_COMMIT_FIELD: &str = "codegraphCommit";

/// The git rev this testkit binary was built from, embedded by `build.rs`.
/// Empty when the build environment has no git metadata (e.g. a path-dep
/// consumer build outside a checkout) — comparison is then impossible and the
/// check warns instead.
pub fn ops_rev() -> &'static str {
    option_env!("CODEGRAPH_OPS_REV").unwrap_or("")
}

/// Verify the freshly generated output at `app_dir` was produced by a
/// generator whose rev matches the rev this testkit was built from.
///
/// Call AFTER a successful regeneration in every suite that regenerates
/// (api `regenerate()`, e2e `e2e_generate`, workers `regenerate`) so the
/// message/behavior is identical everywhere. A mismatch is a hard
/// [`OpsError::TestFailure`] unless `allow_mismatch` (`--allow-gen-rev-
/// mismatch`) downgrades it to a warning.
pub fn check_generator_rev(app_dir: &Path, allow_mismatch: bool) -> OpsResult<()> {
    check_generator_rev_with(app_dir, allow_mismatch, ops_rev())
}

/// [`check_generator_rev`] with an injected pinned rev (tests).
fn check_generator_rev_with(
    app_dir: &Path,
    allow_mismatch: bool,
    pinned_rev: &str,
) -> OpsResult<()> {
    let manifest_path = app_dir.join(GEN_MANIFEST_FILENAME);
    let content = match std::fs::read_to_string(&manifest_path) {
        Ok(content) => content,
        Err(_) => {
            output::warn(format!(
                "no {} under {} — generator rev freshness cannot be checked \
                 (older generator); continuing",
                GEN_MANIFEST_FILENAME,
                app_dir.display()
            ));
            return Ok(());
        }
    };
    let gen_rev: Option<String> = serde_json::from_str::<serde_json::Value>(&content)
        .ok()
        .and_then(|v| {
            v.get(CODEGRAPH_COMMIT_FIELD)
                .and_then(|f| f.as_str())
                .map(str::to_string)
        });
    let Some(gen_rev) = gen_rev.filter(|s| !s.is_empty()) else {
        output::warn(format!(
            "{} carries no usable `{CODEGRAPH_COMMIT_FIELD}` — generator rev \
             freshness cannot be checked; continuing",
            manifest_path.display()
        ));
        return Ok(());
    };
    if pinned_rev.is_empty() {
        output::warn(
            "testkit has no embedded rev (path-dep or non-git build) — generator \
             rev freshness cannot be checked; continuing",
        );
        return Ok(());
    }
    if gen_rev == pinned_rev {
        output::info(format!("Generator rev fresh ({})", short(&gen_rev)));
        return Ok(());
    }
    let msg = format!(
        "generator rev mismatch: {} was generated by rev {} but this testkit was \
         built from rev {} — rebuild the graph binary from the pinned rev so the \
         tested output matches the pinned generators",
        manifest_path.display(),
        gen_rev,
        pinned_rev
    );
    if allow_mismatch {
        output::warn(msg);
        return Ok(());
    }
    Err(OpsError::TestFailure(msg))
}

/// First 12 chars of a rev for log lines (full revs stay in errors).
fn short(rev: &str) -> String {
    rev.chars().take(12).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn app_dir_with_commit(dir: &tempfile::TempDir, commit: Option<&str>) -> PathBuf {
        let app = dir.path().join("generated-app");
        std::fs::create_dir_all(&app).unwrap();
        let json = match commit {
            Some(rev) => format!(r#"{{"codegraphCommit":"{rev}","files":[]}}"#),
            None => r#"{"files":[]}"#.to_string(),
        };
        std::fs::write(app.join(GEN_MANIFEST_FILENAME), json).unwrap();
        app
    }

    const PINNED: &str = "aaaa1111aaaa1111aaaa1111aaaa1111aaaa1111";
    const GENERATED: &str = "bbbb2222bbbb2222bbbb2222bbbb2222bbbb2222";

    #[test]
    fn matching_revs_pass() {
        let dir = tempfile::tempdir().unwrap();
        let app = app_dir_with_commit(&dir, Some(PINNED));
        check_generator_rev_with(&app, false, PINNED).unwrap();
    }

    #[test]
    fn mismatch_is_hard_error_naming_both_revs_and_path() {
        let dir = tempfile::tempdir().unwrap();
        let app = app_dir_with_commit(&dir, Some(GENERATED));
        let err = check_generator_rev_with(&app, false, PINNED).unwrap_err();
        assert!(matches!(err, OpsError::TestFailure(_)), "got {err:?}");
        let msg = err.to_string();
        assert!(msg.contains("generator rev mismatch"), "{msg}");
        assert!(
            msg.contains(GENERATED),
            "must name the generator rev: {msg}"
        );
        assert!(msg.contains(PINNED), "must name the pinned rev: {msg}");
        assert!(
            msg.contains(&app.join(GEN_MANIFEST_FILENAME).display().to_string()),
            "must name the manifest path: {msg}"
        );
    }

    #[test]
    fn mismatch_with_allow_downgrades_to_warning() {
        let dir = tempfile::tempdir().unwrap();
        let app = app_dir_with_commit(&dir, Some(GENERATED));
        check_generator_rev_with(&app, true, PINNED).unwrap();
    }

    #[test]
    fn missing_manifest_warns_and_continues() {
        let dir = tempfile::tempdir().unwrap();
        let app = dir.path().join("generated-app");
        std::fs::create_dir_all(&app).unwrap();
        check_generator_rev_with(&app, false, PINNED).unwrap();
        // Missing app dir entirely is equally non-fatal.
        check_generator_rev_with(&dir.path().join("nowhere"), false, PINNED).unwrap();
    }

    #[test]
    fn missing_or_empty_commit_field_warns_and_continues() {
        let dir = tempfile::tempdir().unwrap();
        let no_field = app_dir_with_commit(&dir, None);
        check_generator_rev_with(&no_field, false, PINNED).unwrap();

        let dir = tempfile::tempdir().unwrap();
        let app = dir.path().join("generated-app");
        std::fs::create_dir_all(&app).unwrap();
        std::fs::write(app.join(GEN_MANIFEST_FILENAME), r#"{"codegraphCommit":""}"#).unwrap();
        check_generator_rev_with(&app, false, PINNED).unwrap();
    }

    #[test]
    fn invalid_manifest_json_warns_and_continues() {
        let dir = tempfile::tempdir().unwrap();
        let app = dir.path().join("generated-app");
        std::fs::create_dir_all(&app).unwrap();
        std::fs::write(app.join(GEN_MANIFEST_FILENAME), "}{ broken").unwrap();
        check_generator_rev_with(&app, false, PINNED).unwrap();
    }

    #[test]
    fn empty_embedded_rev_warns_instead_of_comparing() {
        let dir = tempfile::tempdir().unwrap();
        // Even a mismatching generator rev cannot be judged without a pin.
        let app = app_dir_with_commit(&dir, Some(GENERATED));
        check_generator_rev_with(&app, false, "").unwrap();
    }

    #[test]
    fn constants_match_the_generator_side() {
        assert_eq!(GEN_MANIFEST_FILENAME, ".codegraph-manifest.json");
        assert_eq!(CODEGRAPH_COMMIT_FIELD, "codegraphCommit");
        // The embedded rev is either a full hex SHA or empty (non-git build).
        let rev = ops_rev();
        assert!(rev.is_empty() || (rev.len() == 40 && rev.chars().all(|c| c.is_ascii_hexdigit())));
    }
}
