use std::env;
use std::fs;
use std::io::Write;
use std::path::Path;

fn walk_templates(dir: &Path, base: &Path, names: &mut Vec<(String, String)>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path
                .strip_prefix(base)
                .map(|relative| relative.starts_with(Path::new("ifml").join("packs")))
                .unwrap_or(false)
            {
                // Pack template overrides are resolved from disk on demand
                // (built_in_pack_template_dir); never embed them as built-ins.
                continue;
            }
            if path.is_dir() {
                walk_templates(&path, base, names);
            } else if path.extension().and_then(|e| e.to_str()) == Some("tera") {
                let relative = path.strip_prefix(base).unwrap();
                let name = relative.to_string_lossy().replace('\\', "/");
                let abs = path.to_string_lossy().replace('\\', "\\\\");
                names.push((name.to_string(), abs));
            }
        }
    }
}

/// FNV-1a 64-bit — dependency-free deterministic content hash. The rev
/// only needs to be stable for one binary vs its own scaffolds, so a
/// simple hash beats pulling in a crypto dependency.
fn fnv1a(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf29ce484222325;
    for b in bytes {
        hash ^= u64::from(*b);
        hash = hash.wrapping_mul(0x100_0000_01b3);
    }
    hash
}

fn main() {
    let templates_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("templates");
    if templates_dir.is_dir() {
        let out_dir = env::var("OUT_DIR").unwrap();
        let dest_path = Path::new(&out_dir).join("embedded_templates.rs");
        let mut out = fs::File::create(&dest_path).unwrap();

        writeln!(
            out,
            "// AUTO-GENERATED by build.rs — DO NOT EDIT.\n\
             // Embeds all .tera templates so the binary is self-contained.\n"
        )
        .unwrap();

        writeln!(
            out,
            "pub fn add_embedded_templates(tera: &mut tera::Tera) -> std::result::Result<(), tera::Error> {{"
        )
        .unwrap();

        let mut templates = Vec::new();
        walk_templates(&templates_dir, &templates_dir, &mut templates);
        templates.sort();

        // Template rev (issue #348): a content hash over the `project/`
        // category (what `codegraph init` renders), embedded in the binary
        // via `project_template_rev()` and stamped into every scaffold so
        // doctor can flag wrappers rendered by different templates.
        let mut rev = fnv1a(b"codegraph-project-templates");
        for (name, abs) in templates
            .iter()
            .filter(|(name, _)| name.starts_with("project/"))
        {
            let content = fs::read(abs).unwrap_or_default();
            let mut feed = rev.to_le_bytes().to_vec();
            feed.extend_from_slice(name.as_bytes());
            feed.push(b'\n');
            feed.extend_from_slice(&content);
            feed.push(b'\n');
            rev = fnv1a(&feed);
        }
        println!("cargo:rustc-env=CODEGRAPH_TEMPLATE_REV={rev:016x}");

        // tera 2 validates include/extends/filter references in
        // finalize_templates, which runs at the end of every add_raw_template
        // call — forward includes between templates only resolve if the whole
        // batch is inserted first via a single add_raw_templates call.
        writeln!(out, "    tera.add_raw_templates(vec![").unwrap();

        for (name, abs) in &templates {
            writeln!(
                out,
                "    (\"{name}\", include_str!(\"{abs}\")),",
                name = name,
                abs = abs,
            )
            .unwrap();
        }

        writeln!(out, "])?;").unwrap();
        writeln!(out, "    Ok(())").unwrap();
        writeln!(out, "}}").unwrap();

        println!("cargo:rerun-if-changed=templates/");
        println!(
            "cargo:warning=embedded {} .tera template files",
            templates.len()
        );
    } else {
        eprintln!("cargo:warning=codegraph templates dir not found");
    }
}
