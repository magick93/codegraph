#[cfg(test)]
mod tests {
    use super::*;

    /// The shared contract both planes must keep: the context pair and the
    /// creator come from the same library surface, and the created form is
    /// exported under the same name the page templates import.
    #[test]
    fn both_planes_share_the_createformcreator_contract() {
        for (label, context) in [
            ("entity", ENTITY_FORM_CONTEXT_TS),
            ("ifml", IFML_FORM_CONTEXT_TS),
        ] {
            assert!(
                context.contains("createFormCreatorContexts()"),
                "{label} contexts must come from createFormCreatorContexts:\n{context}"
            );
            assert!(
                context.contains("export const { useFieldContext, useFormContext }"),
                "{label} contexts must export the field/form pair:\n{context}"
            );
        }
        for (label, form) in [("entity", ENTITY_FORM_TS), ("ifml", IFML_FORM_TS)] {
            assert!(
                form.contains("createFormCreator({"),
                "{label} creator must register through createFormCreator:\n{form}"
            );
            assert!(
                form.contains("fieldComponents:") && form.contains("formComponents:"),
                "{label} creator must declare both component registries:\n{form}"
            );
            assert!(
                form.contains("createAppForm"),
                "{label} creator must export createAppForm (the page templates' import):\n{form}"
            );
        }
    }

    /// The entity plane registers the reset affordance as a form component
    /// (issue #574 ledger): the actions row renders `<form.ResetButton>`,
    /// which only resolves when the registration carries it.
    #[test]
    fn entity_library_registers_the_reset_button() {
        assert!(
            ENTITY_FORM_TS.contains("import ResetButton from './fields/ResetButton.svelte';")
                && ENTITY_FORM_TS.contains("ResetButton,"),
            "the entity library must register ResetButton:\n{ENTITY_FORM_TS}"
        );
    }
}
