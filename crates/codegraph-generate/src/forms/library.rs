//! The two planes' `$lib/forms` TanStack scaffold sources, colocated (the
//! #580 "cannot drift" contract made physical). The entity plane
//! (`ui::scaffold`) and the IFML plane (`ifml::route_generator::
//! forms_plane`) each emit `form-context.ts` + `form.ts` if-absent into
//! their own trees; the SOURCES live here side by side so the contract —
//! one `createFormCreatorContexts()` context pair, one `createAppForm`
//! creator over `@tanstack/svelte-form` — is reviewable in one place and
//! the invariant test below pins the shared surface. The two planes'
//! registrations differ DELIBERATELY (entity: PascalCase component files +
//! the SubscribeButton/ResetButton form components; IFML: lowercase files,
//! pages drive `form.Subscribe` inline) — the byte shapes are pinned
//! verbatim by the plane-level tests (`entity_form_tests`,
//! `ifml_tanstack_forms_tests`) and the flag-off canaries.

/// The ENTITY plane's form contexts (`ui/src/lib/forms/form-context.ts`).
pub const ENTITY_FORM_CONTEXT_TS: &str = r#"// Generated by codegraph. DO NOT EDIT.
//
// The TanStack Form field/form contexts (issue #580): field components
// call `useFieldContext()` inside their component script; form components
// call `useFormContext()` (inside a `form.AppForm` wrapper).
import { createFormCreatorContexts } from '@tanstack/svelte-form';

export const { useFieldContext, useFormContext } = createFormCreatorContexts();
"#;

