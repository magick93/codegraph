//! The shared server-side API contract (issue #574 S1): ONE helper source
//! for every generated SvelteKit tree. The entity plane's `+page.server.ts`
//! loads and the IFML plane's remote functions both fetch through
//! `$lib/server/api`, so consumers get one origin/auth story and the API
//! origin and its credentials never reach the client bundle (`$lib/server/**`
//! is SvelteKit's server-only convention — a client import is a build
//! error, the structural guardrail keeping credentials server-side).

/// The module path every consumer imports the helper from.
pub const SERVER_API_IMPORT: &str = "$lib/server/api";

/// The TypeScript source of `src/lib/server/api.ts`. Shared verbatim by
/// both planes' emitters (`ui::scaffold` if-absent; `ifml::route_generator`
/// when a remote module needs it) so the contract cannot drift apart.
pub fn server_api_helper_ts() -> &'static str {
    SERVER_API_TS
}

const SERVER_API_TS: &str = r#"// Generated by codegraph. DO NOT EDIT.
//
// Server-side API plane (issues #557 + #574): every server-side fetch —
// the entity plane's +page.server.ts loads and the IFML plane's remote
// functions — runs through this helper, so the API origin and its
// credentials never reach the client. The origin resolves API_ORIGIN (the
// deprecated IFML_API_ORIGIN spelling is still accepted). The
// Authorization header resolves in order:
//   1. an explicit caller header (loads pass the session's locals.apiKey),
//   2. the incoming request's Authorization header (per-persona test keys
//      arrive this way on remote-function RPCs, keeping row-level
//      isolation real),
//   3. the request's Supabase cookie session (hooks.server.ts parks it on
//      locals.apiKey),
//   4. the deployment's API_KEY env (deprecated IFML_API_KEY spelling
//      still accepted).

import { env } from '$env/dynamic/private';
import { getRequestEvent } from '$app/server';

const API_ORIGIN = env.API_ORIGIN ?? env.IFML_API_ORIGIN ?? '';
const API_KEY = env.API_KEY ?? env.IFML_API_KEY ?? '';

function forwardedAuth(): string | null {
	try {
		const event = getRequestEvent();
		const header = event.request.headers.get('authorization');
		if (header) {
			return header;
		}
		const locals = event.locals as { apiKey?: string } | undefined;
		return locals?.apiKey ?? null;
	} catch {
		// Outside a request scope (e.g. build/prerender): nothing to forward.
		return null;
	}
}

export async function apiFetch(path: string, init: RequestInit = {}): Promise<Response> {
	const headers = new Headers(init.headers);
	if (!headers.has('Authorization')) {
		const forwarded = forwardedAuth();
		if (forwarded) {
			headers.set('Authorization', forwarded);
		} else if (API_KEY) {
			headers.set('Authorization', `Bearer ${API_KEY}`);
		}
	}
	if (!headers.has('Accept')) {
		headers.set('Accept', 'application/json');
	}
	return fetch(`${API_ORIGIN}${path}`, { ...init, headers });
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn helper_resolves_the_neutral_envs_with_deprecated_fallbacks() {
        let helper = server_api_helper_ts();
        assert!(
            helper.contains("env.API_ORIGIN ?? env.IFML_API_ORIGIN"),
            "{helper}"
        );
        assert!(
            helper.contains("env.API_KEY ?? env.IFML_API_KEY"),
            "{helper}"
        );
        assert!(!helper.contains("PUBLIC_API_"), "{helper}");
    }

    #[test]
    fn helper_precedence_is_caller_header_then_request_then_session_then_env() {
        let helper = server_api_helper_ts();
        // An explicit caller header wins — the loads pass the session's
        // locals.apiKey through it.
        assert!(
            helper.contains("if (!headers.has('Authorization'))"),
            "{helper}"
        );
        // Request header before the session leg (persona isolation on RPCs).
        let forwarded = helper
            .find("function forwardedAuth")
            .expect("forwardedAuth");
        let header_leg = helper
            .find("headers.get('authorization')")
            .expect("header leg");
        let session_leg = helper.find("locals?.apiKey").expect("session leg");
        assert!(
            forwarded < header_leg && header_leg < session_leg,
            "{helper}"
        );
        // The env key is the last leg inside apiFetch.
        let env_leg = helper.find("Bearer ${API_KEY}").expect("env leg");
        assert!(session_leg < env_leg, "{helper}");
    }
}
