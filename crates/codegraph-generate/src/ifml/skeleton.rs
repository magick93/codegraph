//! Global generator emitting the SvelteKit project skeleton that the
//! IFML-generated pages compile and run against: package.json (SvelteKit
//! toolchain + scripts), vite.config.ts (`/api` proxy), svelte.config.js,
//! tsconfig.json, and the app shell (`src/app.html`, `src/app.d.ts`).
//!
//! Every file is written only when absent — user customizations and
//! hand-edits survive regeneration. The skeleton supersedes the IFML e2e
//! generator's minimal e2e-only package.json stub: this generator runs (and
//! writes) before the parallel global phase, so the stub's if-absent check
//! resolves in favor of the full toolchain.

use crate::ProjectConfig;
use std::path::{Path, PathBuf};

use async_trait::async_trait;
use codegraph_config::DomainConfig;
use codegraph_core::traits::GraphQuerier;

use crate::error::Result;
use crate::traits::{GeneratedFile, GlobalGenerator};
use crate::GenerationEntry;

/// Global generator emitting the SvelteKit skeleton (svelte only).
pub struct IfmlSkeletonGenerator {
    output_dir: PathBuf,
    framework: String,
}

impl IfmlSkeletonGenerator {
    pub fn new(output_dir: &Path, framework: &str) -> Self {
        Self {
            output_dir: output_dir.to_path_buf(),
            framework: framework.to_string(),
        }
    }
}

#[async_trait]
impl GlobalGenerator for IfmlSkeletonGenerator {
    fn name(&self) -> &str {
        "ifml-skeleton"
    }

    fn sequential_first(&self) -> bool {
        true
    }

    async fn generate(
        &self,
        _db: &dyn GraphQuerier,
        _config: &DomainConfig,
        _generation_order: &[GenerationEntry],
        _tera: &tera::Tera,
        _project: &ProjectConfig,
    ) -> Result<Vec<GeneratedFile>> {
        if self.framework != "svelte" {
            return Ok(vec![]);
        }

        let files = [
            ("package.json", PACKAGE_JSON),
            ("vite.config.ts", VITE_CONFIG),
            ("svelte.config.js", SVELTE_CONFIG),
            ("tsconfig.json", TSCONFIG),
            ("src/app.html", APP_HTML),
            ("src/app.d.ts", APP_D_TS),
        ];
        Ok(files
            .into_iter()
            .filter(|(rel, _)| !self.output_dir.join(rel).exists())
            .map(|(rel, content)| GeneratedFile {
                path: self.output_dir.join(rel),
                content: content.to_string(),
            })
            .collect())
    }
}

