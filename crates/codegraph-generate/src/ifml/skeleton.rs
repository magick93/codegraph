#[cfg(test)]
mod tests {
    use super::*;
    use codegraph_core::mock::MockEngine;

    fn test_config() -> DomainConfig {
        toml::from_str(
            r#"
[defaults]
api_version = "v1"

[domains.sales]
label = "Sales"
schema_dir = "sales"
postgres_schema = "sales"
entities = ["CustomerType"]
"#,
        )
        .unwrap()
    }

    #[test]
    fn skeleton_files_are_never_overwritten() {
        let dir = tempfile::tempdir().unwrap();
        let gen = IfmlSkeletonGenerator::new(dir.path(), "svelte");
        let existing = dir.path().join("src/app.html");
        std::fs::create_dir_all(existing.parent().unwrap()).unwrap();
        std::fs::write(&existing, "<!-- custom shell -->").unwrap();

        let files = futures::executor::block_on(gen.generate(
            &MockEngine::new(),
            &test_config(),
            &[],
            &tera::Tera::default(),
            &ProjectConfig::default(),
        ))
        .unwrap();

        let paths: Vec<String> = files
            .iter()
            .map(|f| f.path.file_name().unwrap().to_string_lossy().to_string())
            .collect();
        assert!(paths.contains(&"package.json".to_string()));
        assert!(paths.contains(&"vite.config.ts".to_string()));
        assert!(
            !paths.iter().any(|p| p == "app.html"),
            "existing src/app.html must not be regenerated: {paths:?}"
        );
    }

    #[test]
    fn package_json_carries_toolchain_and_scripts() {
        assert!(PACKAGE_JSON.contains("@sveltejs/kit"));
        assert!(PACKAGE_JSON
            .contains("\"check\": \"svelte-kit sync && svelte-check --tsconfig ./tsconfig.json\""));
        assert!(PACKAGE_JSON.contains("svelte\": \"^5.56.0"));
    }

    #[test]
    fn vite_config_proxies_api_without_auth_injection() {
        assert!(VITE_CONFIG.contains("process.env.IFML_API_ORIGIN ?? 'http://127.0.0.1:3000'"));
        assert!(VITE_CONFIG.contains("'/api'"));
        assert!(!VITE_CONFIG.contains("authorization"), "{VITE_CONFIG}");
    }
}
