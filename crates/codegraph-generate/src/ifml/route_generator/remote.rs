//! The remote-functions data plane (issue #557): when the
//! `ifml_remote_functions` flag is on, every svelte view gains a colocated
//! `data.remote.ts` whose `query`/`command` exports execute on the
//! SvelteKit server and post through `$lib/server/api`. The browser only
//! ever calls kit's generated same-origin RPC endpoints — the API origin
//! (`IFML_API_ORIGIN`) and its credentials (`IFML_API_KEY`, or the
//! incoming request's Authorization header, e.g. a per-persona test key)
//! never reach the client. A relative same-origin fetch dies under a split
//! gateway topology and an unauthenticated request 401s at the gateway;
//! this plane removes both failure modes at once.
//!
//! Auth forwarding order (in [`SERVER_API_TS`]): the incoming RPC
//! request's `Authorization` header first (Playwright persona contexts
//! attach per-persona keys at the network layer, so RLS isolation stays
//! real), then the deployment's `IFML_API_KEY`.

use super::context::{PageLoadComponentContext, PageLoadContext, RemoteCommand, RemoteCommandKind};

/// The module path every view's `data.remote.ts` imports the shared
/// server-side fetch helper from. `$lib/server/**` is SvelteKit's
/// server-only convention — importing it from client code is a build
/// error, which is the guardrail that keeps the credentials server-side.
pub(crate) const SERVER_API_IMPORT: &str = "$lib/server/api";

/// One query export: the load's single fetch (list / item / form) lowered
/// to a `query('unchecked', ...)`.
pub(super) struct RemoteQuery {
    /// Export name (`getGrid`).
    export: String,
    /// Collection path (`/api/v1/sales/customer`).
    base_path: String,
    /// Entity label for the failure message.
    entity: String,
    paginate: bool,
    workflow: bool,
    /// Item/form query: fetches by id instead of the collection.
    by_id: bool,
}

/// One command export: submit / transition / action op lowered to a
/// `command('unchecked', ...)`.
pub(super) struct RemoteCommandSpec {
    command: RemoteCommand,
}

/// The exports one view's `data.remote.ts` carries, collected from the
/// page + load contexts.
pub(super) struct RemoteModuleContext {
    pub(super) queries: Vec<RemoteQuery>,
    pub(super) commands: Vec<RemoteCommandSpec>,
}

impl RemoteModuleContext {
    pub(super) fn is_empty(&self) -> bool {
        self.queries.is_empty() && self.commands.is_empty()
    }

    /// Collect from a view's load context (the query leg).
    pub(super) fn from_load(load: &PageLoadContext) -> Self {
        let queries = load
            .components
            .iter()
            .filter_map(|comp: &PageLoadComponentContext| {
                comp.remote_query.as_ref().map(|export| RemoteQuery {
                    export: export.clone(),
                    base_path: comp
                        .api
                        .as_ref()
                        .map(|api| api.base_path.clone())
                        .unwrap_or_default(),
                    entity: comp.entity.to_lowercase(),
                    paginate: comp.paginate,
                    workflow: comp.workflow,
                    by_id: comp.fetch_item || comp.fetch_form,
                })
            })
            .collect();
        Self {
            queries,
            commands: Vec::new(),
        }
    }

    pub(super) fn push_command(&mut self, command: &RemoteCommand) {
        self.commands.push(RemoteCommandSpec {
            command: command.clone(),
        });
    }

    /// Render the `data.remote.ts` module source.
    pub(super) fn render(&self) -> String {
        let mut s = String::new();
        s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
        s.push_str("//\n");
        s.push_str("// (views) data plane (issue #557): remote functions run SERVER-side —\n");
        s.push_str("// the browser only calls the generated same-origin endpoints, so the API\n");
        s.push_str("// origin and its credentials never reach the client.\n\n");
        let needs_query = !self.queries.is_empty();
        let needs_command = !self.commands.is_empty();
        let imports = match (needs_query, needs_command) {
            (true, true) => "import { command, query } from '$app/server';",
            (true, false) => "import { query } from '$app/server';",
            (false, true) => "import { command } from '$app/server';",
            (false, false) => "",
        };
        if !imports.is_empty() {
            s.push_str(imports);
            s.push('\n');
        }
        if needs_query {
            s.push_str("import { error } from '@sveltejs/kit';\n");
        }
        s.push_str(&format!(
            "import {{ apiFetch }} from '{SERVER_API_IMPORT}';\n"
        ));
        for q in &self.queries {
            s.push('\n');
            s.push_str(&render_query(q));
        }
        for c in &self.commands {
            s.push('\n');
            s.push_str(&render_command(&c.command));
        }
        s
    }
}

fn render_query(q: &RemoteQuery) -> String {
    let mut s = String::new();
    if q.by_id {
        s.push_str(&format!(
            "export const {export_} = query('unchecked', async (id: string) => {{\n",
            export_ = q.export
        ));
        s.push_str(&format!(
            "\tconst response = await apiFetch(`{base}/${{id}}`);\n",
            base = q.base_path
        ));
        s.push_str("\tif (!response.ok) {\n");
        s.push_str(&format!(
            "\t\terror(response.status, 'Failed to load {entity}');\n",
            entity = q.entity
        ));
        s.push_str("\t}\n");
        s.push_str("\tconst json = await response.json();\n");
        s.push_str("\tconst item = json.data ?? json;\n");
        if q.workflow {
            s.push_str(&format!(
                "\tconst wf = await apiFetch(`{base}/${{id}}/workflow`);\n",
                base = q.base_path
            ));
            s.push_str("\tif (wf.ok) {\n");
            s.push_str("\t\tconst wfJson = await wf.json();\n");
            s.push_str("\t\titem.workflow_state = wfJson.data ?? wfJson;\n");
            s.push_str("\t}\n");
        }
        s.push_str("\treturn item;\n");
    } else {
        if q.paginate {
            s.push_str(&format!(
                "export const {export_} = query('unchecked', async (args: {{ page: string; pageSize: string }}) => {{\n",
                export_ = q.export
            ));
            s.push_str(&format!(
                "\tconst response = await apiFetch(`{base}?page=${{args.page}}&page_size=${{args.pageSize}}`);\n",
                base = q.base_path
            ));
        } else {
            s.push_str(&format!(
                "export const {export_} = query('unchecked', async () => {{\n",
                export_ = q.export
            ));
            s.push_str(&format!(
                "\tconst response = await apiFetch(`{base}`);\n",
                base = q.base_path
            ));
        }
        s.push_str("\tif (!response.ok) {\n");
        s.push_str(&format!(
            "\t\terror(response.status, 'Failed to load {entity}');\n",
            entity = q.entity
        ));
        s.push_str("\t}\n");
        s.push_str("\tconst data = await response.json();\n");
        s.push_str("\treturn Array.isArray(data) ? data : data.data ?? [];\n");
    }
    s.push_str("});\n");
    s
}

fn render_command(c: &RemoteCommand) -> String {
    let mut s = String::new();
    match &c.kind {
        RemoteCommandKind::Create | RemoteCommandKind::Update => {
            s.push_str(&format!(
                "export const {export_} = command('unchecked', async (args: {{ id: string | null; data: Record<string, unknown> }}) => {{\n",
                export_ = c.export
            ));
            s.push_str(&format!(
                "\tconst response = await apiFetch(args.id ? `{base}/${{args.id}}` : `{base}`, {{\n",
                base = c.base_path
            ));
            s.push_str("\t\tmethod: args.id ? 'PUT' : 'POST',\n");
            s.push_str("\t\theaders: { 'Content-Type': 'application/json' },\n");
            s.push_str("\t\tbody: JSON.stringify(args.data)\n");
            s.push_str("\t});\n");
        }
        RemoteCommandKind::Transition => {
            s.push_str(&format!(
                "export const {export_} = command('unchecked', async (args: {{ id: string; to: string }}) => {{\n",
                export_ = c.export
            ));
            s.push_str(&format!(
                "\tconst response = await apiFetch(`{base}/${{args.id}}/actions/transition`, {{\n",
                base = c.base_path
            ));
            s.push_str("\t\tmethod: 'POST',\n");
            s.push_str("\t\theaders: { 'Content-Type': 'application/json' },\n");
            s.push_str("\t\tbody: JSON.stringify({ target_state: args.to })\n");
            s.push_str("\t});\n");
        }
        RemoteCommandKind::Op(op) => {
            s.push_str(&format!(
                "export const {export_} = command('unchecked', async (args: {{ id: string }}) => {{\n",
                export_ = c.export
            ));
            s.push_str(&format!(
                "\tconst response = await apiFetch(`{base}/${{args.id}}/actions/{op}`, {{\n",
                base = c.base_path
            ));
            s.push_str("\t\tmethod: 'POST',\n");
            s.push_str("\t\theaders: { 'Content-Type': 'application/json' },\n");
            s.push_str("\t\tbody: JSON.stringify({})\n");
            s.push_str("\t});\n");
        }
    }
    s.push_str("\tif (!response.ok) {\n");
    s.push_str("\t\tconst body = await response.json().catch(() => null);\n");
    s.push_str("\t\treturn { ok: false, message: body?.error ?? body?.message ?? `Request failed (${response.status})` };\n");
    s.push_str("\t}\n");
    s.push_str("\treturn { ok: true };\n");
    s.push_str("});\n");
    s
}

/// The shared server-side fetch helper (`src/lib/server/api.ts`), emitted
/// once per output tree when any remote module is emitted. `$lib/server/**`
/// is SvelteKit's server-only convention — a client import is a build
/// error, the structural guardrail keeping credentials server-side.
pub(crate) fn render_server_api_helper() -> String {
    SERVER_API_TS.to_string()
}

const SERVER_API_TS: &str = r#"// Generated by codegraph. DO NOT EDIT.
//
// (views) server-side API plane (issue #557): the view remote functions
// execute here, on the SvelteKit server, so the API origin and its
// credentials never reach the client. Every call resolves IFML_API_ORIGIN
// and carries an Authorization header: the incoming RPC request's header
// first (per-persona test keys arrive this way, keeping row-level
// isolation real), then the deployment's IFML_API_KEY.

import { env } from '$env/dynamic/private';
import { getRequestEvent } from '$app/server';

const API_ORIGIN = env.IFML_API_ORIGIN ?? '';
const API_KEY = env.IFML_API_KEY ?? '';

function forwardedAuth(): string | null {
	try {
		const event = getRequestEvent();
		return event.request.headers.get('authorization');
	} catch {
		// Outside a request scope (e.g. build/prerender): nothing to forward.
		return null;
	}
}

export async function apiFetch(path: string, init: RequestInit = {}): Promise<Response> {
	const headers = new Headers(init.headers);
	const forwarded = forwardedAuth();
	if (forwarded) {
		headers.set('Authorization', forwarded);
	} else if (API_KEY) {
		headers.set('Authorization', `Bearer ${API_KEY}`);
	}
	if (!headers.has('Accept')) {
		headers.set('Accept', 'application/json');
	}
	return fetch(`${API_ORIGIN}${path}`, { ...init, headers });
}
"#;
