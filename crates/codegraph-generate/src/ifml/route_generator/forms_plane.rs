const SELECT_VARIANT_SVELTE: &str = r#"<!-- Generated by codegraph. DO NOT EDIT. -->
<!-- The selection-field slot variant (issue #574 ledger): composes the
     project's NativeSelect barrel — a REAL shadcn Select is not
     AppField-slot-compatible (snippet-rendered items) and would break the
     POM's selectOption fill, so the pack's selection-field entry points
     HERE: a native <select> with the generator-owned name/testid/
     required/options around the declared value/onchange wiring. Emitted
     if-absent when a selection-field mapping carries field_props. -->
<script lang="ts">
	import * as NativeSelect from '$lib/components/ui/native-select/index.js';

	interface Props {
		value?: string;
		onchange?: (value: string) => void;
		options?: string[];
		name?: string;
		testid?: string;
		required?: boolean;
	}

	let {
		value = undefined,
		onchange,
		options = [],
		name = undefined,
		testid = undefined,
		required = undefined
	}: Props = $props();
</script>

<NativeSelect.Root
	name={name}
	required={required}
	value={value}
	onchange={(e) => onchange?.(e.currentTarget.value)}
	data-testid={testid}
>
	{#each options as option (option)}
		<NativeSelect.Option value={option}>{option}</NativeSelect.Option>
	{/each}
</NativeSelect.Root>
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn form_ts_wires_the_creator_and_exports_the_rune() {
        assert!(FORM_TS.contains("createFormCreator({"));
        assert!(FORM_TS.contains("formComponents: {}"));
        assert!(FORM_TS.contains("export { createAppForm };"));
    }

    #[test]
    fn form_context_exports_the_contexts_hook() {
        assert!(FORM_CONTEXT_TS.contains("createFormCreatorContexts"));
        assert!(FORM_CONTEXT_TS.contains("useFieldContext"));
    }

    #[test]
    fn every_field_component_consumes_the_context_and_carries_the_message_attr() {
        for (name, source) in [
            ("text", FIELD_TEXT),
            ("email", FIELD_EMAIL),
            ("number", FIELD_NUMBER),
            ("checkbox", FIELD_CHECKBOX),
            ("select", FIELD_SELECT),
            ("datetime", FIELD_DATETIME),
            ("textarea", FIELD_TEXTAREA),
            ("radio", FIELD_RADIO),
        ] {
            assert!(
                source.contains("useFieldContext"),
                "{name}.svelte must consume the field context"
            );
            assert!(
                source.contains("data-validate-message"),
                "{name}.svelte must carry the message attribute"
            );
            assert!(
                source.contains("required={required}"),
                "{name}.svelte must keep the native required attr"
            );
        }
    }

    #[test]
    fn select_and_radio_interpolate_options_through_svelte_bindings() {
        // The #560 escape surface: option values never interpolate raw.
        assert!(FIELD_SELECT.contains("<option value={v}>{v}</option>"));
        assert!(FIELD_RADIO.contains("value={v}"));
    }
}
