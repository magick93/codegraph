//! The IFML form-creator scaffold (issue #580): the
//! `@tanstack/svelte-form` wiring every TanStack page variant imports —
//! `$lib/forms/form.ts` (`createFormCreator` → `createAppForm`),
//! `$lib/forms/form-context.ts` (`createFormCreatorContexts`), and one
//! field component per control kind under `$lib/forms/fields/`.
//!
//! The SOURCES live here as Rust consts so the entity plane's #580 half
//! cannot drift from this one (same lesson as the shared server-api
//! helper, issue #574 S1). Emission is if-absent, once per output tree —
//! the `src/lib/server/api.ts` mechanism from the remote-functions plane —
//! so hand edits and entity-plane copies survive regeneration.
//!
//! Field components consume `useFieldContext()` (set by
//! `<form.AppField>`), bind `field.state.value`/`handleChange`, keep the
//! native `required` attribute (the e2e `validity.valid` contract), and
//! render `data-validate-message` from the first live error — a mapped
//! 422 field detail, else the first zod issue, else the model's static
//! message. All prose reaches emitted TS through `forms::ts_string_literal`
//! at the page-context layer and Svelte `{...}` interpolation here (the
//! #560 lesson applied to the flag-ON path).

use std::path::Path;

use crate::traits::GeneratedFile;

/// Emit the form plane's files; skips every path that already exists.
pub(crate) fn form_plane_files(output_dir: &Path) -> Vec<GeneratedFile> {
    let files: [(&str, &str); 10] = [
        ("src/lib/forms/form-context.ts", FORM_CONTEXT_TS),
        ("src/lib/forms/form.ts", FORM_TS),
        ("src/lib/forms/fields/text.svelte", FIELD_TEXT),
        ("src/lib/forms/fields/email.svelte", FIELD_EMAIL),
        ("src/lib/forms/fields/number.svelte", FIELD_NUMBER),
        ("src/lib/forms/fields/checkbox.svelte", FIELD_CHECKBOX),
        ("src/lib/forms/fields/select.svelte", FIELD_SELECT),
        ("src/lib/forms/fields/datetime.svelte", FIELD_DATETIME),
        ("src/lib/forms/fields/textarea.svelte", FIELD_TEXTAREA),
        ("src/lib/forms/fields/radio.svelte", FIELD_RADIO),
    ];
    files
        .into_iter()
        .filter(|(rel, _)| !output_dir.join(rel).exists())
        .map(|(rel, content)| GeneratedFile {
            path: output_dir.join(rel),
            content: content.to_string(),
        })
        .collect()
}

/// Emit the selection-field variant wrapper (`select-variant.svelte`) —
/// if-absent, ONLY when the mappings carry a wired selection-field entry
/// (the wrapper imports the project's NativeSelect barrel; a no-shadcn
/// tree must never carry a dangling barrel import).
pub(crate) fn form_plane_files_select_variant(output_dir: &Path, wired: bool) {
    if !wired {
        return;
    }
    let path = output_dir.join("src/lib/forms/fields/select-variant.svelte");
    if path.exists() {
        return;
    }
    let _ = std::fs::create_dir_all(path.parent().expect("parent"));
    let _ = std::fs::write(path, SELECT_VARIANT_SVELTE);
}

/// The `(export, import path)` a field-component export resolves to — the
/// page context routes the imports through the template's shared import
/// loop. `None` for names outside the scaffold.
pub(crate) fn component_import(component: &str) -> Option<(&'static str, &'static str)> {
    const COMPONENTS: &[(&str, &str)] = &[
        ("TextField", "$lib/forms/fields/text.svelte"),
        ("EmailField", "$lib/forms/fields/email.svelte"),
        ("NumberField", "$lib/forms/fields/number.svelte"),
        ("CheckboxField", "$lib/forms/fields/checkbox.svelte"),
        ("SelectField", "$lib/forms/fields/select.svelte"),
        ("DatetimeField", "$lib/forms/fields/datetime.svelte"),
        ("TextAreaField", "$lib/forms/fields/textarea.svelte"),
        ("RadioField", "$lib/forms/fields/radio.svelte"),
    ];
    COMPONENTS
        .iter()
        .find(|(name, _)| *name == component)
        .map(|(name, path)| (*name, *path))
}

