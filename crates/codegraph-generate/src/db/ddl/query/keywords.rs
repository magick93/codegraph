/// Spell an identifier for direct embedding in a SQL fragment (check
/// expressions) and for the render-time quoting pass. Identifier fields
/// on the DDL model stay bare (#451) — quoting happens at render time.
pub(in crate::db::ddl) fn quote_if_reserved(name: &str) -> String {
    if PG_RESERVED_WORDS.contains(name.to_lowercase().as_str()) {
        format!("\"{}\"", name)
    } else {
        name.to_string()
    }
}

/// Wrap a string value in PostgreSQL dollar-quoting.
/// Uses `$$` by default; if the value contains `$$`, falls back to `$q$...$q$`.
pub(super) fn dollar_quote(val: &str) -> String {
    if val.contains("$$") {
        format!("$q${}$q$", val)
    } else {
        format!("$${}$$", val)
    }
}

/// Strip the Rust `r#` keyword escaping prefix from a SQL identifier.
/// This prevents `#` characters from leaking into constraint names
/// (e.g. fk_certification_r#type → fk_certification_type).
pub(super) fn strip_rsharp(name: &str) -> String {
    name.strip_prefix("r#").unwrap_or(name).to_string()
}
