//! The entity remote-functions data plane (issue #574 S2): when the
//! `entity_remote_functions` flag is on, every entity route gains a
//! colocated `data.remote.ts` whose `query`/`command` exports execute on
//! the SvelteKit server and post through the shared `$lib/server/api`
//! helper (issue #574 S1). The browser stores (`#lib/stores/*`) and the
//! `PUBLIC_API_KEY` client plane retire — the browser only calls kit's
//! same-origin RPC endpoints, and the loads/pages keep their contracts so
//! the POM/e2e surface holds.
//!
//! One module per route, carrying only what that route uses (the IFML
//! #573 precedent): the list route gets `getList` (+ `deleteItem` under
//! the ux row-action plane), the detail route `getItem` (+ transition /
//! delete commands + child-section queries), the edit route
//! `getItem`/`updateItem`, the create route `createItem`.
//!
//! Command contracts return discriminated `{ ok }` unions (`as const`)
//! so pages can surface `message`/`id` without non-discriminated
//! property errors.

use super::page::{UiPageContext, UiPageMediaField};

fn push_header(s: &mut String) {
    s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
    s.push_str("//\n");
    s.push_str("// Entity data plane (issue #574 S2): remote functions run SERVER-side —\n");
    s.push_str("// the browser only calls the generated same-origin endpoints, so the API\n");
    s.push_str("// origin and its credentials never reach the client.\n\n");
}

/// The interpolated collection path: hierarchy holes interpolate
/// `args.parentId`/`args.grandparentId` so the server-side function
/// receives the route params from its caller (the load).
fn path_expr_string(ctx: &UiPageContext, api_version: &str) -> String {
    let mut p = String::from("/api/");
    p.push_str(api_version);
    p.push('/');
    if let Some(parent) = &ctx.parent {
        if let Some(gp) = &parent.grandparent {
            p.push_str(&gp.domain);
            p.push('/');
            p.push_str(&gp.path_segment);
            p.push_str("/${args.grandparentId}/");
            p.push_str(&parent.path_segment);
            p.push_str("/${args.parentId}/");
        } else {
            p.push_str(&parent.domain);
            p.push('/');
            p.push_str(&parent.path_segment);
            p.push_str("/${args.parentId}/");
        }
    } else {
        p.push_str(&ctx.domain);
        p.push('/');
    }
    p.push_str(&ctx.path_segment);
    p
}

fn push_path_expr(s: &mut String, ctx: &UiPageContext, api_version: &str) {
    let mut p = path_expr_string(ctx, api_version);
    p.insert(0, '`');
    p.push('`');
    s.push_str(&p);
}

/// The interpolated item path: collection path + `/${id}` (or
/// `/${args.id}` inside commands).
fn item_path(ctx: &UiPageContext, api_version: &str, id_expr: &str) -> String {
    let mut p = path_expr_string(ctx, api_version);
    p.push('/');
    p.push_str(id_expr);
    p
}

/// The hierarchy arg fields for a function args type (empty for roots).
fn hierarchy_arg_fields(ctx: &UiPageContext) -> String {
    match &ctx.parent {
        Some(p) => {
            if p.grandparent.is_some() {
                "grandparentId: string; parentId: string; ".to_string()
            } else {
                "parentId: string; ".to_string()
            }
        }
        None => String::new(),
    }
}

/// The read-by-id function's positional parameter list (subset per
/// nesting depth).
fn hierarchy_id_params(ctx: &UiPageContext) -> String {
    match &ctx.parent {
        Some(p) => {
            if p.grandparent.is_some() {
                "id: string, parentId: string, grandparentId: string".to_string()
            } else {
                "id: string, parentId: string".to_string()
            }
        }
        None => "id: string".to_string(),
    }
}

/// Interpolate the hierarchy path segment for read-by-id calls: root has
/// no hole; child appends `/${parentId}`; grandchild
/// `/${grandparentId}/${parentId}` BEFORE the parent segment — expressed
/// as the full prefix built in [item_path_from_ids].
fn item_path_from_ids(ctx: &UiPageContext, api_version: &str) -> String {
    let mut p = String::from("/api/");
    p.push_str(api_version);
    p.push('/');
    if let Some(parent) = &ctx.parent {
        if let Some(gp) = &parent.grandparent {
            p.push_str(&gp.domain);
            p.push('/');
            p.push_str(&gp.path_segment);
            p.push_str("/${grandparentId}/");
            p.push_str(&parent.path_segment);
            p.push_str("/${parentId}/");
        } else {
            p.push_str(&parent.domain);
            p.push('/');
            p.push_str(&parent.path_segment);
            p.push_str("/${parentId}/");
        }
    } else {
        p.push_str(&ctx.domain);
        p.push('/');
    }
    p.push_str(&ctx.path_segment);
    p.push_str("/${id}");
    p
}

fn list_query(ctx: &UiPageContext, api_version: &str) -> String {
    let mut s = String::new();
    s.push_str(
        "export const getList = query('unchecked', async (args: { page: string; pageSize: string;",
    );
    if ctx.has_fts {
        s.push_str(" q: string;");
    }
    if ctx.ux_sort.is_some() {
        s.push_str(" sort: string; order: string;");
    }
    s.push(' ');
    s.push_str(&hierarchy_arg_fields(ctx));
    s.push_str("}) => {\n");
    s.push_str(
        "\tconst params = new URLSearchParams({ page: args.page, page_size: args.pageSize });\n",
    );
    if ctx.has_fts {
        s.push_str("\tif (args.q) params.set('q', args.q);\n");
    }
    if ctx.ux_sort.is_some() {
        s.push_str("\tif (args.sort) {\n\t\tparams.set('sort', args.sort);\n\t\tparams.set('order', args.order === 'desc' ? 'desc' : 'asc');\n\t}\n");
    }
    s.push_str("\tconst base = ");
    push_path_expr(&mut s, ctx, api_version);
    s.push_str(";\n");
    s.push_str("\tconst response = await apiFetch(`${base}?${params.toString()}`);\n");
    s.push_str("\tif (!response.ok) {\n");
    s.push_str(&format!(
        "\t\terror(response.status, 'Failed to load {} list');\n",
        ctx.entity_name.to_lowercase()
    ));
    s.push_str("\t}\n");
    s.push_str("\tconst data = await response.json();\n");
    s.push_str("\treturn Array.isArray(data) ? data : data.data ?? [];\n");
    s.push_str("});\n");
    s
}

fn item_query(ctx: &UiPageContext, api_version: &str) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "export const getItem = query('unchecked', async ({}) => {{\n",
        hierarchy_id_params(ctx)
    ));
    s.push_str("\tconst response = await apiFetch(");
    s.push_str(&format!("`{}`", item_path_from_ids(ctx, api_version)));
    s.push_str(");\n");
    s.push_str("\tif (!response.ok) {\n");
    s.push_str(&format!(
        "\t\terror(response.status, 'Failed to load {}');\n",
        ctx.entity_name.to_lowercase()
    ));
    s.push_str("\t}\n");
    s.push_str("\tconst json = await response.json();\n");
    s.push_str("\tconst item = json.data ?? json;\n");
    if ctx.has_workflow {
        // Workflow merge: same path + /workflow.
        let mut wf = item_path_from_ids(ctx, api_version);
        wf.push_str("/workflow");
        s.push_str("\ttry {\n");
        s.push_str("\t\tconst wf = await apiFetch(`");
        s.push_str(&wf);
        s.push_str("`);\n");
        s.push_str("\t\tif (wf.ok) {\n");
        s.push_str("\t\t\tconst wfJson = await wf.json();\n");
        s.push_str("\t\t\titem.workflow_state = wfJson.data ?? wfJson;\n");
        s.push_str("\t\t}\n");
        s.push_str("\t} catch {\n");
        s.push_str("\t\t// Workflow state not available — panel will be hidden\n");
        s.push_str("\t}\n");
    }
    s.push_str("\treturn item;\n");
    s.push_str("});\n");
    s
}

fn child_queries(ctx: &UiPageContext, api_version: &str) -> String {
    let mut s = String::new();
    for section in &ctx.child_sections {
        s.push_str(&format!(
            "export const get{}Children = query('unchecked', async (id: string) => {{\n",
            section.entity_name
        ));
        s.push_str("\tconst response = await apiFetch(`/api/");
        s.push_str(api_version);
        s.push('/');
        s.push_str(&section.domain);
        s.push('/');
        s.push_str(&section.path_segment);
        s.push_str("?parent_id=${id}`);\n");
        s.push_str("\tif (!response.ok) {\n\t\treturn [];\n\t}\n");
        s.push_str("\tconst data = await response.json();\n");
        s.push_str("\treturn Array.isArray(data) ? data : data.data ?? [];\n");
        s.push_str("});\n\n");
        // The child section's delete rides a command too — the component
        // receives it as the `onDelete` callback (issue #574 S2: no
        // browser fetch plane). The parent id rides along so the command
        // can key the children query instance for the single-flight
        // refresh (issue #574 S4a).
        //
        // Kit 3 remote functions take ONE input argument (`command(validate,
        // fn: (arg: Input) => …)` — there is no multi-argument overload), so
        // the pair travels as an object (issue #634).
        s.push_str(&format!(
            "export const delete{}Child = command('unchecked', async ({{ childId, parentId }}: {{ childId: string; parentId: string }}) => {{\n",
            section.entity_name
        ));
        s.push_str("\tconst response = await apiFetch(`/api/");
        s.push_str(api_version);
        s.push('/');
        s.push_str(&section.domain);
        s.push('/');
        s.push_str(&section.path_segment);
        s.push_str("/${childId}`, {\n\t\tmethod: 'DELETE',\n\t});\n");
        s.push_str(COMMAND_FAIL_LEG);
        s.push_str(&format!(
            "\tvoid get{}Children(parentId).refresh();\n",
            section.entity_name
        ));
        s.push_str("\treturn { ok: true as const };\n");
        s.push_str("});\n\n");
    }
    s
}

/// The commands' shared failure leg (discriminated `{ ok: false }`).
///
/// The API's error body is `{ error: { code, message, details? } }` — the
/// pre-#634 legs read `body?.error ?? …`, which stringified the OBJECT
/// into the toast (`[object Object]`). Read the message field (issue #634,
/// the #582 IFML-plane lesson applied one plane over).
const COMMAND_FAIL_LEG: &str = "\tif (!response.ok) {\n\t\tconst body = await response.json().catch(() => null);\n\t\treturn { ok: false as const, message: body?.error?.message ?? body?.message ?? `Request failed (${response.status})` };\n\t}\n";

/// The create/update failure leg under the TanStack form layer (issue
/// #580): the 422 `VALIDATION_ERROR` body's `details: [{field, message}]`
/// parse into `fieldErrors` so the form can map them onto the matching
/// fields. The union shape keeps `fieldErrors` present on EVERY `!ok`
/// member (empty when the API sent no details) so callers can read it
/// after narrowing on `ok`.
const COMMAND_FAIL_LEG_FIELD_ERRORS: &str = "\tif (!response.ok) {\n\t\tconst body = await response.json().catch(() => null);\n\t\tconst fieldErrors: Record<string, string> = {};\n\t\tconst details = body?.error?.details;\n\t\tif (Array.isArray(details)) {\n\t\t\tfor (const d of details) {\n\t\t\t\tif (d && typeof d.field === 'string' && typeof d.message === 'string') {\n\t\t\t\t\tfieldErrors[d.field] = d.message;\n\t\t\t\t}\n\t\t\t}\n\t\t}\n\t\treturn { ok: false as const, message: body?.error?.message ?? body?.message ?? `Request failed (${response.status})`, fieldErrors };\n\t}\n";

fn create_command(ctx: &UiPageContext, api_version: &str, entity_form: bool) -> String {
    let mut s = String::new();
    s.push_str("export const createItem = command('unchecked', async (args: { data: Record<string, unknown>; ");
    s.push_str(&hierarchy_arg_fields(ctx));
    s.push_str("}) => {\n");
    s.push_str("\tconst response = await apiFetch(");
    push_path_expr(&mut s, ctx, api_version);
    s.push_str(", {\n");
    s.push_str("\t\tmethod: 'POST',\n");
    s.push_str("\t\theaders: { 'Content-Type': 'application/json' },\n");
    s.push_str("\t\tbody: JSON.stringify(args.data),\n");
    s.push_str("\t});\n");
    if entity_form {
        s.push_str(COMMAND_FAIL_LEG_FIELD_ERRORS);
    } else {
        s.push_str(COMMAND_FAIL_LEG);
    }
    s.push_str("\tconst json = await response.json();\n");
    s.push_str("\treturn { ok: true as const, id: (json.data ?? json).id as string };\n");
    s.push_str("});\n");
    s
}

fn update_command(ctx: &UiPageContext, api_version: &str, entity_form: bool) -> String {
    let mut s = String::new();
    s.push_str("export const updateItem = command('unchecked', async (args: { id: string; data: Record<string, unknown>; ");
    s.push_str(&hierarchy_arg_fields(ctx));
    s.push_str("}) => {\n");
    s.push_str("\tconst response = await apiFetch(");
    s.push_str(&format!("`{}`", item_path(ctx, api_version, "${args.id}")));
    s.push_str(", {\n");
    s.push_str("\t\tmethod: 'PUT',\n");
    s.push_str("\t\theaders: { 'Content-Type': 'application/json' },\n");
    s.push_str("\t\tbody: JSON.stringify(args.data),\n");
    s.push_str("\t});\n");
    if entity_form {
        s.push_str(COMMAND_FAIL_LEG_FIELD_ERRORS);
    } else {
        s.push_str(COMMAND_FAIL_LEG);
    }
    // Single-flight refresh (issue #574 S4a): the edited row rides the
    // command response back to the client's query instance.
    s.push_str("\tvoid getItem(args.id).refresh();\n");
    s.push_str("\treturn { ok: true as const };\n");
    s.push_str("});\n");
    s
}

