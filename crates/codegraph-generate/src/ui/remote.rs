/// The media display URL (issue #633): the route 307s to the provider's
/// (signed) URL, so the FINAL response URL is the renderable one — resolved
/// server-side because the media route is behind the API auth middleware.
fn media_display_query(ctx: &UiPageContext, api_version: &str, media: &UiPageMediaField) -> String {
    let mut path = item_path(ctx, api_version, "${id}");
    path.push('/');
    path.push_str(&media.field);
    let mut s = String::new();
    s.push_str(&format!(
        "export const get{}Display = query('unchecked', async (id: string) => {{\n",
        media.pascal
    ));
    s.push_str(&format!("\tconst response = await apiFetch(`{path}`);\n"));
    s.push_str("\tif (!response.ok) {\n\t\treturn { url: null as string | null };\n\t}\n");
    // No redirect ⇒ nothing the browser could render (the route always
    // redirects on a stored reference; a same-URL body would need auth).
    s.push_str("\tvoid response.body?.cancel();\n");
    s.push_str("\treturn { url: response.redirected ? response.url : (null as string | null) };\n");
    s.push_str("});\n");
    s
}

/// The multipart upload command (issue #633): the bytes never reach the
/// browser's credentials — the server-side helper posts the FormData (fetch
/// sets the boundary, so no Content-Type is set) and the route persists the
/// reference row. The result carries the provider URL so the page can render
/// the display without a second round trip.
fn media_upload_command(
    ctx: &UiPageContext,
    api_version: &str,
    media: &UiPageMediaField,
) -> String {
    let mut path = item_path(ctx, api_version, "${args.id}");
    path.push('/');
    path.push_str(&media.field);
    let mut s = String::new();
    s.push_str(&format!(
        "export const upload{} = command('unchecked', async (args: {{ id: string; file: File }}) => {{\n",
        media.pascal
    ));
    s.push_str("\tconst form = new FormData();\n");
    s.push_str("\tform.append('file', args.file, args.file.name);\n");
    s.push_str(&format!(
        "\tconst response = await apiFetch(`{path}`, {{\n\t\tmethod: 'PUT',\n\t\tbody: form,\n\t}});\n"
    ));
    s.push_str("\tconst body = await response.json().catch(() => null);\n");
    s.push_str("\tif (!response.ok) {\n");
    s.push_str(
        "\t\treturn { ok: false as const, message: body?.error?.message ?? `Upload failed (${response.status})` };\n",
    );
    s.push_str("\t}\n");
    s.push_str(
        "\treturn { ok: true as const, key: body?.key as string | undefined, url: body?.url as string | undefined };\n",
    );
    s.push_str("});\n");
    s
}

