fn needs_query_import(queries: &[bool]) -> bool {
    queries.iter().any(|q| *q)
}

fn needs_command_import(commands: &[bool]) -> bool {
    commands.iter().any(|c| *c)
}

fn assemble(
    header_done: &mut String,
    queries: usize,
    commands: usize,
    bodies: &[String],
) -> String {
    let mut s = std::mem::take(header_done);
    let q = queries > 0;
    let c = commands > 0;
    match (q, c) {
        (true, true) => s.push_str("import { command, query } from '$app/server';\n"),
        (true, false) => s.push_str("import { query } from '$app/server';\n"),
        (false, true) => s.push_str("import { command } from '$app/server';\n"),
        (false, false) => {}
    }
    if q {
        s.push_str("import { error } from '@sveltejs/kit';\n");
    }
    s.push_str("import { apiFetch } from '$lib/server/api';\n");
    for body in bodies {
        s.push('\n');
        s.push_str(body);
    }
    let _ = (needs_query_import(&[q]), needs_command_import(&[c]));
    s
}

/// The list route's module: `getList` (+ `deleteItem` when the ux
/// row-action plane exposes delete on the list).
pub(super) fn render_list_module(
    ctx: &UiPageContext,
    api_version: &str,
    ux_delete: bool,
) -> String {
    let mut bodies = Vec::new();
    let mut queries = 0usize;
    let mut commands = 0usize;
    if ctx.has_list {
        bodies.push(list_query(ctx, api_version));
        queries += 1;
    }
    if ux_delete && ctx.has_delete {
        bodies.push(delete_command(ctx, api_version));
        commands += 1;
    }
    let mut header = String::new();
    push_header(&mut header);
    assemble(&mut header, queries, commands, &bodies)
}

/// The detail route's module: `getItem`, the transition/delete commands,
/// and one child-list query per config child section. Under the
/// live-query plane (`ui_live_queries`, issue #574 S4c) a workflow-bound
/// entity also carries a `getWorkflowLive` stream: a 5s poll of the
/// `/workflow` read whose yields update the client's reactive instance —
/// the load payload stays the SSR fallback.
pub(super) fn render_detail_module(ctx: &UiPageContext, api_version: &str, live: bool) -> String {
    let mut bodies = Vec::new();
    let mut queries = 0usize;
    let mut commands = 0usize;
    // The transition command single-flight-refreshes `getItem` (issue #574
    // S4a), so the read query is emitted whenever ANYTHING in the module
    // refreshes it — not only when the page reads the record (issue #634:
    // a workflow without the read op referenced an unexported refresh
    // target).
    if ctx.has_read || ctx.has_workflow {
        bodies.push(item_query(ctx, api_version));
        queries += 1;
    }
    if ctx.has_workflow {
        bodies.push(transition_command(ctx, api_version));
        commands += 1;
        if live {
            bodies.push(workflow_live_query(ctx, api_version));
            queries += 1;
        }
    }
    if ctx.has_delete {
        bodies.push(delete_command(ctx, api_version));
        commands += 1;
    }
    // Media plane (issue #633): one display query + upload/remove commands
    // per media field with an app-plane route. The bytes never touch the
    // browser's credentials — the upload posts multipart FormData through
    // the shared server helper (fetch sets the multipart boundary itself,
    // so no Content-Type header is set here).
    for media in &ctx.media_fields {
        bodies.push(media_display_query(ctx, api_version, media));
        queries += 1;
        bodies.push(media_upload_command(ctx, api_version, media));
        commands += 1;
        bodies.push(media_remove_command(ctx, api_version, media));
        commands += 1;
    }
    let children = child_queries(ctx, api_version);
    if !children.is_empty() {
        bodies.push(children);
        // One list query + one delete command per section.
        queries += ctx.child_sections.len();
        commands += ctx.child_sections.len();
    }
    let mut header = String::new();
    push_header(&mut header);
    assemble(&mut header, queries, commands, &bodies)
}

/// The edit route's module: `getItem` + `updateItem`. Under the TanStack
/// form layer (`entity_form`, issue #580) the update command's fail leg
/// parses 422 details into `fieldErrors`.
pub(super) fn render_edit_module(
    ctx: &UiPageContext,
    api_version: &str,
    entity_form: bool,
) -> String {
    let mut bodies = Vec::new();
    let mut queries = 0usize;
    let mut commands = 0usize;
    if ctx.has_update {
        bodies.push(item_query(ctx, api_version));
        queries += 1;
        bodies.push(update_command(ctx, api_version, entity_form));
        commands += 1;
    }
    let mut header = String::new();
    push_header(&mut header);
    assemble(&mut header, queries, commands, &bodies)
}

/// The create route's module: `createItem`. Under the TanStack form layer
/// (`entity_form`, issue #580) the create command's fail leg parses 422
/// details into `fieldErrors`.
pub(super) fn render_create_module(
    ctx: &UiPageContext,
    api_version: &str,
    entity_form: bool,
) -> String {
    let mut bodies = Vec::new();
    let mut commands = 0usize;
    if ctx.has_create {
        bodies.push(create_command(ctx, api_version, entity_form));
        commands += 1;
    }
    let mut header = String::new();
    push_header(&mut header);
    assemble(&mut header, 0, commands, &bodies)
}

