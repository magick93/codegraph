//! Entity ui gate (issue #574 S2): the generated entity SvelteKit app
//! TYPECHECKS and BUILDS under the `entity_remote_functions` flag.
//!
//! Its absence is how the kit-3 `$app/env/public` break went unnoticed —
//! the entity ui tree was never compiled anywhere in this repo (the
//! @crewbase workspace deps only resolve in consumer monorepos), so
//! template breaks shipped silently. The gate regenerates the review
//! fixture in place (the same recipe `review_api_suite` uses), stubs the
//! consumer-monorepo packages (`@crewbase/entities` / `@crewbase/ui` /
//! `@crewbase/common`), builds the app (vite — which also compiles the
//! paraglide messages the pages import), then runs svelte-check against
//! the generated paraglide output. Zero type errors is the bar.
//!
//! ```text
//! cargo test -p codegraph --test entity_codegen_gate -- --ignored --nocapture
//! ```
//!
//! No `--test-threads` flag: the gate self-serializes (issue #694). Both
//! tests provision, build and check ONE committed fixture tree, so they take
//! an in-process [`GATE_LOCK`] for their whole body, and the shared provision
//! step (`review_api_suite_regen::FixtureGate::provision`) additionally
//! takes the cross-process [`review_api_suite_regen::FixtureGate`] — the same
//! fixture is regenerated by `review_api_suite` and `rules_guard_api_gate`,
//! which are separate binaries. Provisioning regenerates FROM CLEAN (the
//! previous generation's files are swept first), so a stale artifact of an
//! older generation can never be compiled, discovered by playwright, or hurl'd
//! as this run's — the #688 class, which a shared tree otherwise invites.
//!
//! Needs node 22 + npx. The entity e2e lane (`entity_specs_run_green`,
//! issue #575) holds the emitted-config coverage invariant over every
//! emitted test file and runs the sessionless `auth` project live against
//! a booted API over `vite preview`; the UI-driven families stay the
//! consumer `testkit e2e` lane (they need the Supabase persona stack).
//!
//! Diagnostic attribution (issues #634, #728): svelte-check prints the file
//! path on the line BEFORE the `Error:`/`Warn:` line, so the pre-#634
//! assertion (which filtered lines containing `"Error:"`) could never match
//! a path and the "zero diagnostics on generated paths" gate was vacuous.
//! #634 repaired the parser against that human shape — and #728 showed the
//! repair was still ANSI-blind: under CI svelte-check colourises `Error:`
//! and the summary line, so every `strip_prefix` missed, the attribution set
//! came back empty and the gate died on its own reconciliation check (while
//! masking ten real diagnostics). The gate therefore parses svelte-check's
//! `--output machine-verbose` ndjson contract instead — `START` /
//! `ERROR` / `WARNING` / `COMPLETED` / `FAILURE` records, no colour,
//! filenames resolved against the `START` workspace. It RECONCILES the
//! parsed error count against the `COMPLETED … ERRORS` count (and the exit
//! status), and asserts on every diagnostic inside a GENERATED path.
//! Consumer-authored / gate-owned paths are reported explicitly (and written
//! to `target/entity-gate/consumer-diagnostics.txt`) instead of silently
//! disappearing.

