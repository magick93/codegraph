/// One entity-gate test at a time (issue #694). Both tests provision, build
/// and check the same committed fixture tree, so a parallel libtest run would
/// corrupt itself — the historical `--test-threads=1` requirement. The mutex
/// replaces it: the gate is correct under any thread count, and a subset run
/// (one test by name) sees the same from-clean tree the workflow run does. The
/// cross-process half lives in `review_api_suite_regen::FixtureGate` (the same
/// fixture is regenerated by two other gate binaries).
static GATE_LOCK: OnceLock<tokio::sync::Mutex<()>> = OnceLock::new();

fn gate_lock() -> &'static tokio::sync::Mutex<()> {
    GATE_LOCK.get_or_init(|| tokio::sync::Mutex::new(()))
}

