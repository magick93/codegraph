// ── svelte-check report parsing (issue #634) ────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Severity {
    Error,
    Warn,
}

#[derive(Debug, Clone)]
struct Diagnostic {
    path: PathBuf,
    line: u32,
    column: u32,
    severity: Severity,
    message: String,
}

impl Diagnostic {
    /// The path relative to the fixture's `ui/` directory, `/`-normalized
    /// when the diagnostic points inside it.
    fn ui_relative(&self, ui: &Path) -> Option<String> {
        let rel = self.path.strip_prefix(ui).ok()?;
        Some(rel.to_string_lossy().replace('\\', "/"))
    }
}

/// svelte-check's machine records are `<millisecond timestamp> <body>`
/// (ndjson for `--output machine-verbose`). A line is a record iff its
/// first space-delimited column is an integer timestamp; everything else
/// (`Loading svelte-check in workspace: …`, `Getting Svelte diagnostics...`,
/// npm/npx noise on the merged stderr) is preamble and is ignored.
fn machine_record_body(line: &str) -> Option<&str> {
    let (timestamp, rest) = line.split_once(' ')?;
    if timestamp.is_empty() || !timestamp.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    Some(rest)
}

/// The payload of a single-string machine record (`START` / `FAILURE`).
fn machine_quoted_payload(payload: &str) -> Result<String, String> {
    serde_json::from_str::<String>(payload.trim()).map_err(|e| format!("{e}: {payload}"))
}

/// Resolve a machine record's filename against the `START` workspace.
///
/// Filenames in the machine format are workspace-RELATIVE. Resolving them is
/// load-bearing, not cosmetic: the gate's `ui_relative` / `consumer_owned`
/// attribution is a prefix match, so an unresolved relative path would land
/// every diagnostic in the consumer bucket — attribution silently degraded
/// is exactly the #634/#728 defect class. `.` segments are normalized away
/// so `strip_prefix(workspace)` yields the clean `src/…` tail. `..` is
/// deliberately NOT collapsed: svelte-check reports `path.relative()`
/// against its workspace, so a `..` means the file is OUTSIDE the report
/// root — rewriting it lexically would fabricate a path, and the
/// `START`-contains-`ui_dir` guard (not this function) is what anchors the
/// root.
fn resolve_machine_path(workspace: &Path, filename: &str) -> PathBuf {
    let candidate = Path::new(filename);
    let joined = if candidate.is_absolute() {
        candidate.to_path_buf()
    } else {
        workspace.join(candidate)
    };
    let mut resolved = PathBuf::new();
    for component in joined.components() {
        match component {
            std::path::Component::CurDir => {}
            other => resolved.push(other.as_os_str()),
        }
    }
    resolved
}

/// The `START` workspace a machine report declares (`None` when the report
/// carries no `START` record at all).
fn machine_start_workspace(output: &str) -> Option<PathBuf> {
    output.lines().find_map(|raw| {
        let body = machine_record_body(raw.trim_end())?;
        let folder = body.strip_prefix("START ")?;
        machine_quoted_payload(folder).ok().map(PathBuf::from)
    })
}

/// Hard guard: the report's `START` workspace must physically CONTAIN the
/// ui dir the gate attributes against (review F2 on issue #728).
///
/// Attribution is a lexical `strip_prefix(ui_dir())`, while `START` is the
/// svelte-check process CWD (physical, `getcwd(2)`) and `ui_dir()` is
/// `CARGO_MANIFEST_DIR`-derived (logical). In a symlinked checkout the two
/// spellings differ, every diagnostic's absolute path then falls outside
/// `ui_dir()` and lands in the CONSUMER bucket — printed, never asserted —
/// while the parsed-vs-`COMPLETED` reconciliation still passes. That is the
/// #634/#728 blindness class one level out, so it is a hard error here.
///
/// Both sides are canonicalized (symlinks resolved); a canonicalization
/// failure is itself named rather than ignored.
fn assert_workspace_covers_ui(workspace: &Path, ui: &Path) -> Result<(), String> {
    let canonical = |path: &Path, what: &str| {
        fs::canonicalize(path).map_err(|e| {
            format!(
                "cannot canonicalize the {what} `{}`: {e} — the gate cannot prove its \
                 diagnostic attribution root, and guessing would silently degrade attribution \
                 (issue #728 review F2)",
                path.display()
            )
        })
    };
    let workspace = canonical(workspace, "START workspace")?;
    let ui = canonical(ui, "ui dir")?;
    if !ui.starts_with(&workspace) {
        return Err(format!(
            "svelte-check's START workspace `{}` does not contain the gate's ui dir `{}` — \
             attribution is a lexical strip_prefix against the ui dir, so every diagnostic \
             would land in the consumer bucket (printed, never asserted) while the \
             parsed-vs-COMPLETED counts still reconcile. That is the #634/#728 blindness with \
             nothing left to catch it (issue #728 review F2). Fix the gate's workspace/ui-dir \
             derivation (symlinked checkout?) rather than widening this guard.",
            workspace.display(),
            ui.display()
        ));
    }
    Ok(())
}

/// `(diagnostics, Some((errors, warnings)))`, both counts from the report's
/// `COMPLETED` record (there is no `None` case on success — a report with no
/// summary is a parser failure).
type CheckReport = (Vec<Diagnostic>, Option<(usize, usize)>);

/// Parse svelte-check's `--output machine-verbose` report.
///
/// The record vocabulary is svelte-check's own (see the CLI's
/// "Machine-readable output" docs, same implementation as the
/// `svelte-check` v4 binary the fixture pins):
///
/// ```text
/// <ts> START "<workspace folder>"
/// <ts> {"type":"ERROR","filename":"src/x.svelte","start":{"line":9,"character":31},
///       "end":{…},"message":"…","code":2307,"source":"js"}
/// <ts> {"type":"WARNING",…}
/// <ts> COMPLETED 20 FILES 21 ERRORS 1 WARNINGS 3 FILES_WITH_PROBLEMS
/// <ts> FAILURE "Connection closed"
/// ```
///
/// Deliberate contract choices (each pinned below, node-free):
///   - `ERROR`/`WARNING` carry `filename` (the released binary) or `fn`
///     (the shape the CLI docs spell in one example) — both are accepted,
///     `filename` preferred.
///   - `start.line`/`start.character` are LSP-zero-based; they are emitted
///     ONE-based (like the human print shape) so rendered attributions keep
///     pointing at the line an IDE links to.
///   - `COMPLETED` counts are read BY LABEL, never by index — a reordered or
///     extended record cannot shift `ERRORS` into the warnings slot.
///   - Anything timestamp-prefixed that this parser cannot read (unknown
///     record type, truncated JSON, missing count label, a diagnostic with
///     no usable filename, a diagnostic before `START`) is a HARD error. A
///     malformed record must never be skipped: skipping is precisely how
///     the ANSI-blind human parser returned an empty attribution set while
///     svelte-check reported ten errors (issue #728).
///   - `FAILURE` and a missing `COMPLETED` are hard errors too — a run that
///     died (or whose summary never printed) must not read as "zero
///     diagnostics".
fn parse_svelte_check_machine(output: &str) -> Result<CheckReport, String> {
    let mut workspace: Option<PathBuf> = None;
    let mut diagnostics: Vec<Diagnostic> = Vec::new();
    let mut summary: Option<(usize, usize)> = None;
    let mut failures: Vec<String> = Vec::new();

    for (index, raw) in output.lines().enumerate() {
        let line = raw.trim_end();
        let Some(body) = machine_record_body(line) else {
            // Human preamble / npm noise — not a record.
            continue;
        };
        let at = format!("line {}", index + 1);

        // Diagnostic records are ndjson OBJECTS whose `type` field names the
        // record (`{"type":"ERROR",…}`) — the released binary, and the docs'
        // own example. START / COMPLETED / FAILURE are bare-word records.
        if body.starts_with('{') {
            let record: serde_json::Value = serde_json::from_str(body)
                .map_err(|e| format!("malformed machine record ({at}, ndjson): {e}: {body}"))?;
            let kind = record
                .get("type")
                .and_then(serde_json::Value::as_str)
                .ok_or_else(|| format!("machine record ({at}) carries no `type` field: {body}"))?;
            if !matches!(kind, "ERROR" | "WARNING") {
                return Err(format!(
                    "unrecognised svelte-check machine record type `{kind}` ({at}) — the gate \
                     understands ERROR/WARNING diagnostic records plus the START/COMPLETED/\
                     FAILURE bookends; a record it cannot read must fail loudly, never vanish \
                     from the attribution set (issue #728): {line}"
                ));
            }
            let severity = if kind == "ERROR" {
                Severity::Error
            } else {
                Severity::Warn
            };
            let filename = record
                .get("filename")
                .or_else(|| record.get("fn"))
                .and_then(serde_json::Value::as_str)
                .filter(|name| !name.is_empty())
                .ok_or_else(|| {
                    format!(
                        "{kind} record ({at}) carries no usable `filename` (or legacy `fn`) \
                         field — the diagnostic cannot be attributed: {body}"
                    )
                })?;
            let start = record.get("start").ok_or_else(|| {
                format!("{kind} record ({at}) carries no `start` position: {body}")
            })?;
            let line_no = start
                .get("line")
                .and_then(serde_json::Value::as_u64)
                .ok_or_else(|| {
                    format!("{kind} record ({at}) carries no numeric `start.line`: {body}")
                })?;
            let character = start
                .get("character")
                .and_then(serde_json::Value::as_u64)
                .ok_or_else(|| {
                    format!("{kind} record ({at}) carries no numeric `start.character`: {body}")
                })?;
            let workspace = workspace.as_ref().ok_or_else(|| {
                format!(
                    "{kind} record ({at}) precedes the START record — filenames are \
                     workspace-relative, so the gate cannot resolve a path: {body}"
                )
            })?;
            let message = record
                .get("message")
                .and_then(serde_json::Value::as_str)
                .unwrap_or_default()
                .to_string();
            diagnostics.push(Diagnostic {
                path: resolve_machine_path(workspace, filename),
                line: one_based(line_no),
                column: one_based(character),
                severity,
                message,
            });
            continue;
        }

        let (kind, payload) = body.split_once(' ').unwrap_or((body, ""));

        match kind {
            "START" => {
                let folder = machine_quoted_payload(payload)
                    .map_err(|e| format!("malformed START record ({at}): {e}"))?;
                if folder.is_empty() {
                    return Err(format!(
                        "START record ({at}) names an empty workspace folder — machine-verbose \
                         filenames are workspace-relative, so nothing can be attributed"
                    ));
                }
                workspace = Some(PathBuf::from(folder));
            }
            "COMPLETED" => {
                let mut errors = None;
                let mut warnings = None;
                let tokens: Vec<&str> = payload.split_whitespace().collect();
                if !tokens.len().is_multiple_of(2) {
                    return Err(format!(
                        "COMPLETED record ({at}) does not carry `<count> <LABEL>` pairs: {line}"
                    ));
                }
                for pair in tokens.chunks(2) {
                    let count: usize = pair[0].parse().map_err(|_| {
                        format!(
                            "COMPLETED record ({at}) carries a non-numeric count `{}`: {line}",
                            pair[0]
                        )
                    })?;
                    // By LABEL, never by index: an extra/reordered segment
                    // must not shift the counts the gate reconciles on.
                    match pair[1] {
                        "ERRORS" => errors = Some(count),
                        "WARNINGS" => warnings = Some(count),
                        _ => {}
                    }
                }
                match (errors, warnings) {
                    (Some(errors), Some(warnings)) => summary = Some((errors, warnings)),
                    _ => {
                        return Err(format!(
                            "COMPLETED record ({at}) is missing its ERRORS and/or WARNINGS \
                             count — the gate reconciles its attribution set against both: {line}"
                        ));
                    }
                }
            }
            "FAILURE" => {
                // A runtime error record: the run died, so the report is not
                // a report. Name the message the binary gave (it is a JSON
                // string; if it is not, keep the raw payload rather than
                // losing it).
                failures.push(
                    machine_quoted_payload(payload).unwrap_or_else(|_| payload.trim().to_string()),
                );
            }
            other => {
                return Err(format!(
                    "unrecognised svelte-check machine record `{other}` ({at}) — the gate \
                     understands the START/COMPLETED/FAILURE bookends plus ndjson \
                     ERROR/WARNING records; a record it cannot read must fail loudly, never \
                     vanish from the attribution set (issue #728): {line}"
                ));
            }
        }
    }

    if !failures.is_empty() {
        return Err(format!(
            "svelte-check reported FAILURE — the run died before producing a report the gate \
             can reconcile: {}",
            failures.join("; ")
        ));
    }
    let Some(summary) = summary else {
        return Err(format!(
            "svelte-check printed no COMPLETED record — the machine report is truncated, and a \
             missing summary is exactly the blindness issue #728 removed (the gate reconciles \
             its attribution set against the compiler's own counts):\n{output}"
        ));
    };
    Ok((diagnostics, Some(summary)))
}

/// Machine records report LSP positions, which are zero-based; the gate
/// renders (and pinned against) the one-based position svelte-check's human
/// output prints.
fn one_based(position: u64) -> u32 {
    u32::try_from(position.saturating_add(1)).unwrap_or(u32::MAX)
}

/// Paths the gate does NOT assert (consumer-authored or gate-owned): the
/// openapi-typescript stub + the consumer api module the fixture's
/// hand-authored forms import, and the hand-authored `src/forms` tree the
/// gate tsconfig excludes. Everything else under `ui/src` is generator
/// output and must typecheck clean — the allowlist is fail-closed (a new
/// generated directory is asserted by default).
///
/// `forms/` (top-level, NOT `src/`) is the legacy cosmos form plane whose
/// imports resolve through the consumer monorepo's design system
/// (`@community-os/ui`) — the gate stubs that package, so a diagnostic
/// there measures the stub, not the generator. Its diagnostics are
/// recorded (printed + written) on every run.
fn consumer_owned(path: &str) -> bool {
    matches!(
        path,
        "src/lib/api/types.ts" | "src/lib/api/index.ts" | "src/forms"
    ) || path.starts_with("src/forms/")
        || path.starts_with("src/lib/paraglide/")
        || path.starts_with("forms/")
}

fn generated_diagnostics<'a>(diagnostics: &'a [Diagnostic], ui: &Path) -> Vec<&'a Diagnostic> {
    diagnostics
        .iter()
        .filter(|d| d.severity == Severity::Error)
        .filter(|d| d.ui_relative(ui).is_some_and(|rel| !consumer_owned(&rel)))
        .collect()
}

fn consumer_diagnostics<'a>(diagnostics: &'a [Diagnostic], ui: &Path) -> Vec<&'a Diagnostic> {
    diagnostics
        .iter()
        .filter(|d| d.severity == Severity::Error)
        .filter(|d| d.ui_relative(ui).is_none_or(|rel| consumer_owned(&rel)))
        .collect()
}

/// A PRE-EXISTING generated-plane defect the repaired gate surfaced that
/// this sweep does NOT fix (issue #634 STOP CONDITION: the gate must never
/// be left permanently red, and the debt must never be silently skipped).
///
/// Shrink-only ratchet:
///   - a generated-path error matching NO entry FAILS the gate;
///   - an entry matching NOTHING FAILS the gate (so a fixed defect cannot
///     linger in the ledger).
///
/// Each entry names where the debt is tracked; the enumerated table lives
/// in `docs/tdd/entity-kit-sweep.tdd.md`.
struct KnownDefect {
    /// `ui/`-relative path prefix.
    path: &'static str,
    /// Substring of the diagnostic message.
    message: &'static str,
    /// Where the work is tracked.
    reference: &'static str,
}

const KNOWN_DEFECTS: &[KnownDefect] = &[KnownDefect {
    path: "src/lib/server/api.ts",
    message: "'$env/dynamic/private'",
    reference: "entity-kit-sweep gap G1 (shared server_api.rs helper: kit 2 ships \
                    $env/dynamic/private, kit 3 moved it to $app/env/private)",
}];

fn render_diagnostic(d: &Diagnostic, ui: &Path) -> String {
    let where_ = d
        .ui_relative(ui)
        .or_else(|| {
            d.path
                .strip_prefix(ui.parent().unwrap_or(ui))
                .ok()
                .map(|p| p.to_string_lossy().replace('\\', "/"))
        })
        .unwrap_or_else(|| d.path.to_string_lossy().into_owned());
    format!("{}:{}:{} — {}", where_, d.line, d.column, d.message)
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "entity ui gate: run with --ignored (needs node)"]
async fn entity_app_builds_and_typechecks() {
    if !have_tool("node") || !have_tool("npx") {
        eprintln!("skipping: node/npx not found");
        return;
    }

    let _guard = gate_lock().lock().await;
    let gate = review_api_suite_regen::FixtureGate::acquire().expect("acquire fixture gate");
    provision_fixture(&gate).await.unwrap();
    stub_crewbase_packages().unwrap();
    stub_api_types().unwrap();

    // The ui-shell plane (descriptor-driven pages) emits a TOP-LEVEL route
    // tree that conflicts with the (app)-grouped entity routes under kit
    // 3's conflict detection — a PRE-EXISTING shell-plane incompatibility
    // (issue #577 ledger), not the entity plane's. The gate builds the
    // entity plane; the shell tree is removed before sync.
    let routes = ui_dir().join("src/routes");
    for shell_dir in ["common", "compensation", "events", "recruiting", "rsvp"] {
        let dir = routes.join(shell_dir);
        if dir.is_dir() {
            fs::remove_dir_all(&dir).map_err(|e| e.to_string()).unwrap();
        }
    }

    let project = svelte_project();
    project.ensure_install().unwrap();
    // Sync BEFORE the root tsconfig: kit generates .svelte-kit/tsconfig.json,
    // which the gate-owned root tsconfig extends (extending the
    // not-yet-generated file hard-errors under the kit-3 vite transform).
    // A prior run's tsconfig lingers in the checked-in fixture — remove it
    // for the bootstrap sync, then write + re-sync.
    let tsconfig = ui_dir().join("tsconfig.json");
    if tsconfig.exists() {
        fs::remove_file(&tsconfig)
            .map_err(|e| e.to_string())
            .unwrap();
    }
    project.sync_sveltekit().unwrap();
    write_gate_tsconfig().unwrap();
    project.sync_sveltekit().unwrap();

    // Sweep the retired store plane (issue #574 S2): this flag-ON provision
    // sweeps only the files ITS OWN previous generation wrote (issue #694), so
    // a store the flag-OFF recipe (`grafeo_candidate_inspect_output`) left in
    // the shared fixture would still linger — importing the retired public key
    // and failing the check. The navigation store is UI state, not an API
    // plane — it stays.
    let stores = ui_dir().join("src/lib/stores");
    if stores.is_dir() {
        for entry in fs::read_dir(&stores).map_err(|e| e.to_string()).unwrap() {
            let path = entry.unwrap().path();
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if name != "entity-navigation.ts" && name.ends_with(".ts") {
                fs::remove_file(&path).unwrap();
            }
        }
    }

    // Build FIRST: the paraglide vite plugin compiles the messages the
    // pages import; svelte-check types against the generated output.
    let ok = project.run_build().unwrap();
    assert!(ok, "vite build failed (see target/entity-gate/logs)");
    assert!(
        ui_dir().join(".svelte-kit/output/client").is_dir(),
        "vite build did not produce .svelte-kit/output artifacts"
    );

    let Ok((check_ok, output)) = project.run_check_machine() else {
        panic!("failed to launch svelte-check");
    };
    // The gate holds the GENERATOR's surface to zero type errors. The
    // fixture also carries consumer-authored artifacts (src/forms/*, the
    // gate-owned api stubs) whose fidelity is not the generator's contract
    // — diagnostics against those are reported, not asserted (issue #634:
    // every one is printed AND written to a file, never silently dropped).
    // The report is svelte-check's `machine-verbose` ndjson (issue #728):
    // the human shape colourises `Error:` under CI, so the old
    // `strip_prefix` parser attributed nothing while the compiler was
    // reporting ten errors.
    let (diagnostics, summary) = parse_svelte_check_machine(&output).unwrap_or_else(|e| {
        panic!("svelte-check machine report unparsable: {e}\n--- output ---\n{output}")
    });
    // The parser resolves record filenames against the report's OWN `START`
    // workspace; the gate attributes against `ui_dir()`. Those must be the
    // same physical tree, or the lexical `strip_prefix` below silently
    // buckets every diagnostic as consumer-owned (issue #728 review F2).
    let report_workspace = machine_start_workspace(&output).unwrap_or_else(|| {
        panic!(
            "svelte-check's machine report carries no START record — the gate cannot verify \
             its attribution root:\n{output}"
        )
    });
    assert_workspace_covers_ui(&report_workspace, &ui_dir()).unwrap_or_else(|e| panic!("{e}"));
    let (reported_errors, _reported_warnings) = summary.unwrap_or_else(|| {
        panic!(
            "svelte-check printed no `COMPLETED` summary record — the gate cannot reconcile its \
             attribution set against the compiler's own count:\n{output}"
        )
    });
    let parsed_errors = diagnostics
        .iter()
        .filter(|d| d.severity == Severity::Error)
        .count();
    assert_eq!(
        parsed_errors, reported_errors,
        "gate parser drift: attributed {parsed_errors} error diagnostic(s) but svelte-check \
         reported {reported_errors}. A mismatch means the report shape moved and the \
         generated-path assertion is blind again (issue #634):\n{output}"
    );
    assert_eq!(
        check_ok,
        reported_errors == 0,
        "svelte-check's exit status ({check_ok}) disagrees with its own summary \
         ({reported_errors} errors) — the gate must fail on the compiler's verdict, not \
         disown it"
    );

    let generated = generated_diagnostics(&diagnostics, &ui_dir());
    let consumer = consumer_diagnostics(&diagnostics, &ui_dir());
    if !consumer.is_empty() {
        let report = consumer
            .iter()
            .map(|d| render_diagnostic(d, &ui_dir()))
            .collect::<Vec<_>>()
            .join("\n");
        fs::write(logs_dir().join("consumer-diagnostics.txt"), &report)
            .map_err(|e| e.to_string())
            .unwrap();
        println!(
            "gate: {} NON-GENERATED (consumer-authored/gate-owned) error(s) — recorded, not \
             asserted (target/entity-gate/consumer-diagnostics.txt):\n{report}",
            consumer.len()
        );
    }
    // Known pre-existing defects (documented, shrink-only ratchet).
    let mut known_hits = vec![0usize; KNOWN_DEFECTS.len()];
    let mut unlisted: Vec<&Diagnostic> = Vec::new();
    for d in &generated {
        let rel = d.ui_relative(&ui_dir()).unwrap_or_default();
        match KNOWN_DEFECTS.iter().position(|k| {
            rel.starts_with(k.path) && d.message.contains(k.message.trim_matches('\''))
        }) {
            Some(idx) => known_hits[idx] += 1,
            None => unlisted.push(d),
        }
    }
    if known_hits.iter().sum::<usize>() > 0 {
        println!(
            "gate: {} documented pre-existing generated-plane defect(s) (see \
             docs/tdd/entity-kit-sweep.tdd.md):",
            known_hits.iter().sum::<usize>()
        );
        for (k, hits) in KNOWN_DEFECTS.iter().zip(&known_hits) {
            if *hits > 0 {
                println!("  - {hits}× {} — {}", k.path, k.reference);
            }
        }
    }
    let stale: Vec<&KnownDefect> = KNOWN_DEFECTS
        .iter()
        .zip(&known_hits)
        .filter(|(_, hits)| **hits == 0)
        .map(|(k, _)| k)
        .collect();
    assert!(
        stale.is_empty(),
        "the known-defect ledger is STALE for {} entr(y/ies) — the defect was fixed (delete \
         the entry) or the diagnostic message moved (re-point it):\n{}",
        stale.len(),
        stale
            .iter()
            .map(|k| format!("{} — {}", k.path, k.reference))
            .collect::<Vec<_>>()
            .join("\n")
    );
    assert!(
        unlisted.is_empty(),
        "svelte-check reported {} UNDOCUMENTED error(s) on GENERATED files (fix them, or add an \
         entry to the known-defect ledger with a tracking reference):\n{}",
        unlisted.len(),
        unlisted
            .iter()
            .map(|d| render_diagnostic(d, &ui_dir()))
            .collect::<Vec<_>>()
            .join("\n")
    );
}

