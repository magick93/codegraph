use std::env;
use std::fs;
use std::io::Write;
use std::path::Path;

fn walk_templates(dir: &Path, base: &Path, names: &mut Vec<(String, String)>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk_templates(&path, base, names);
            } else if path.extension().and_then(|e| e.to_str()) == Some("tera") {
                let relative = path.strip_prefix(base).unwrap();
                let name = relative.to_string_lossy().replace('\\', "/");
                let abs = path.to_string_lossy().replace('\\', "\\\\");
                names.push((name.to_string(), abs));
            }
        }
    }
}

fn main() {
    let templates_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("templates");
    if !templates_dir.is_dir() {
        eprintln!("cargo:warning=codegraph templates dir not found");
        return;
    }

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("embedded_templates.rs");
    let mut out = fs::File::create(&dest_path).unwrap();

    writeln!(
        out,
        "// AUTO-GENERATED by build.rs — DO NOT EDIT.\n\
         // Embeds all .tera templates so the binary is self-contained.\n"
    )
    .unwrap();

    writeln!(
        out,
        "pub fn add_embedded_templates(tera: &mut tera::Tera) -> std::result::Result<(), tera::Error> {{"
    )
    .unwrap();

    let mut templates = Vec::new();
    walk_templates(&templates_dir, &templates_dir, &mut templates);
    templates.sort();

    for (name, abs) in &templates {
        writeln!(
            out,
            "    tera.add_raw_template(\"{name}\", include_str!(\"{abs}\"))?;",
            name = name,
            abs = abs,
        )
        .unwrap();
    }

    writeln!(out, "    Ok(())").unwrap();
    writeln!(out, "}}").unwrap();

    println!("cargo:rerun-if-changed=templates/");
    println!("cargo:warning=embedded {} .tera template files", templates.len());
}
