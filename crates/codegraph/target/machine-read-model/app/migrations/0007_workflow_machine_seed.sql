UPDATE "claims"."claim" AS e
SET "status" = wi.current_state
FROM platform.workflow_instance wi
JOIN platform.workflow_definition wd ON wi.definition_id = wd.id
WHERE wd.domain = 'claims'
  AND wd.entity_table = 'claim'
  AND wd.is_active = true
  AND wi.current_state NOT LIKE 'pending_approval:%'
  AND e.id = wi.entity_id
  AND e."status" IS DISTINCT FROM wi.current_state;

